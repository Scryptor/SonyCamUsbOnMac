import Foundation

/// Уровни превью камеры: какой код камеры (10 бит, 0…1023) стоит за значением канала JPEG live view (0…255).
///
/// Превью растягивает коды 64…1019 — от чёрного уровня видео до самого светлого кода — на всю шкалу 0…255, и в видео, и в
/// фото. Так измерено на ZV-E10 (`scripts/check_log_preview.py`, docs/protocol.md, «Превью в S-Log и HLG»): кадры S-Log2,
/// S-Log3 и HLG одной сцены сходятся друг с другом по формулам Sony только при этом растяжении. Отсюда и знакомые уровни
/// превью: белое видео (код 940, 100 %) — 234, чёрное — 0, белое фото (код 1019) — 255. Чёрное S-Log3 (код 95) в превью — 8,
/// а не 24, 18 % серого (код 420) — 95, а не 105.
///
/// Встроенные LUT считаются по коду камеры `код/1023` — так заданы формулы Sony, и так рассчитаны LUT Sony для монтажных
/// программ, — поэтому вход LUT — не `v = Y′/255`, а `a + b·v` (`code`). Свои `.cube` получают тот же вход.
public enum PreviewLevels {
    /// Код камеры, который в превью — 0: чёрный уровень видео.
    public static let blackCode = 64.0
    /// Сколько кодов камеры занимает вся шкала превью: коды 64…1019 → 0…255.
    public static let codeSpan = 955.0
    /// `a` поправки входа LUT: код/1023 при `v = 0`, 64/1023 ≈ 0,0626.
    public static let offset = blackCode / 1023
    /// `b` поправки входа LUT: на сколько вырастает код/1023 на всю шкалу превью, 955/1023 ≈ 0,9335.
    public static let gain = codeSpan / 1023

    /// Код камеры/1023 для значения канала превью `v = Y′/255`: `a + b·v`.
    public static func code(_ v: Double) -> Double { offset + gain * v }

    /// Значение канала превью (0…1) для кода камеры/1023 — обратное к `code`.
    public static func preview(_ code: Double) -> Double { (code - offset) / gain }

    /// Куб, рассчитанный на код камеры/1023 (встроенный или свой `.cube`, со своим доменом `[min, max]` в тех же
    /// единицах), — для значений превью: домен переводится в значения превью, `(min − a)/b … (max − a)/b`, так что вход `v`
    /// попадает в куб как `a + b·v`. Числа куба те же (тот же массив в памяти), меняется только домен.
    public static func forPreview(_ lut: ColorLUT) -> ColorLUT {
        let a = Float(offset), b = Float(gain)
        return ColorLUT(size: lut.size, values: lut.values,
                        domainMin: lut.domainMin.map { ($0 - a) / b },
                        domainMax: lut.domainMax.map { ($0 - a) / b })
    }
}
