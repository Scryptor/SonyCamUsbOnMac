package local.zve10viewer.session

import local.zve10viewer.ptp.TransportException

/**
 * Камеры, которые не ответили на необязательную операцию новых камер Sony (0x9215, 0x9216, 0x9223) за время ожидания транспорта.
 *
 * Тайм-аут значит, что камера называет операцию в GetDeviceInfo, а отвечать на неё не умеет или не хочет. Слежение за связью
 * закрывает такой сеанс как «камера не отвечает» (15 с без ответа на операцию), тихое переподключение открывает следующий — и
 * программа, спросив то же, снова ждёт без ответа: так по кругу. Поэтому такую камеру о новых операциях больше не спрашиваем до
 * перезапуска программы: подписи Creative Look тогда берутся из таблиц Sony, расстояний на шкале нет. Камера — её id из списка
 * знакомых камер: тот же id — следующий сеанс той же камеры.
 *
 * Не потокобезопасна: ею пользуется один поток (главный, [local.zve10viewer.CameraInfo]).
 */
class SilentCameras {
    private val cameras = HashSet<String>()

    /**
     * Ошибка необязательной операции камеры [camera]. Тайм-аут записывает камеру; всё остальное — отказ камеры, разбор, обрыв
     * связи — нет: они ничего не говорят о том, что в следующий раз будет то же. true — камера записана сейчас впервые (в журнал
     * строка одна). Без id камеры (null) запомнить некого.
     */
    fun note(error: Throwable, camera: String?): Boolean {
        if (camera == null || (error as? TransportException)?.timeout != true) return false
        return cameras.add(camera)
    }

    /** Этой камере необязательные операции не посылаем. */
    fun skips(camera: String?): Boolean = camera != null && camera in cameras
}
