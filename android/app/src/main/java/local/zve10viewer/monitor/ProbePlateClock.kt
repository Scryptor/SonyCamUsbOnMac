package local.zve10viewer.monitor

import kotlinx.coroutines.delay

/**
 * Как часто меняется табличка пипетки: не чаще пяти раз в секунду — кадров до тридцати, и цифры, которые прыгают чаще, не
 * прочитать. Табличка не получает показания от потока кадров, а сама спрашивает последнее раз в [INTERVAL_MS], поэтому предел
 * держится по построению: что бы ни делали кадры, перерисовка, перетаскивание и увеличение. Пока показания нет, спрашивает
 * чаще ([FIRST_LOOK_MS]) — табличка появляется сразу после первого кадра с пипеткой, а не через пятую долю секунды.
 */
object ProbePlateClock {
    /** Столько между двумя опросами, когда показание есть: 200 мс — пять раз в секунду. */
    const val INTERVAL_MS = 200L

    /** Столько между опросами, пока показания нет. */
    const val FIRST_LOOK_MS = 50L

    /**
     * Следит за показанием: [read] — последнее показание (null — нет), [show] зовётся, когда оно изменилось с прошлого раза (и
     * когда исчезло). Не возвращается, пока корутину не отменят.
     */
    suspend fun <T : Any> follow(read: () -> T?, show: (T?) -> Unit) {
        var shown: T? = null
        while (true) {
            val latest = read()
            if (latest != shown) {
                shown = latest
                show(latest)
            }
            delay(if (shown == null) FIRST_LOOK_MS else INTERVAL_MS)
        }
    }
}
