package local.zve10viewer.view

import android.view.KeyEvent

/**
 * Что сделало нажатие клавиши съёмки на экране: пошло ли оно в камеру, а если нет — почему. Строка — для журнала («Отладка», logcat
 * ZVLink): по ней видно, дошла ли клавиша до программы и почему ничего не случилось.
 */
enum class KeyAction(val journalText: String) {
    /** Фоторежим: то же, что кнопка спуска на экране. */
    photo("спуск"),

    /** Видео и S&Q: то же, что кнопка записи на экране — пуск, если не пишет, остановка, если пишет. */
    record("пуск или остановка записи"),

    /** Кадр закрыт: ⚙, пресеты, галерея, отладка, просмотр снимка или карточка-подсказка. Меню Fn, «Монитор» и «Все настройки» кадр не закрывают. */
    elsewhere("не на экране кадра — ничего"),

    /** Камера не на связи или ещё не готова (подключается, настраивается). */
    notReady("камера не готова — ничего"),

    /** Камера ещё не ответила на прошлое нажатие: снимок идёт, запись запускается или останавливается. */
    busy("камера ещё не ответила на прошлое нажатие — ничего"),
}

/** Что делать с событием клавиши: [consumed] — забрать (система его не увидит), [pressed] — это нажатие главной кнопки. */
data class KeyHandling(val consumed: Boolean, val pressed: Boolean)

/**
 * Кнопки громкости и «Камера» (пульты для телефонов шлют те же коды) как главная кнопка съёмки — переключатель в ⚙, по умолчанию
 * выключен: случайная запись хуже, чем лишний поиск в настройках. Правила (спека, §6):
 * - включено: клавиши 24, 25 и 27 программа забирает всегда — и нажатие, и отпускание, и когда ничего не делает: громкость не
 *   прыгает; выключено — не трогает, система меняет громкость как обычно;
 * - действует только нажатие без повтора: удержание не повторяет спуск и не включает и тут же выключает запись;
 * - куда оно идёт — [press]: только на экране кадра и только если кнопка на экране сейчас нажималась бы.
 */
object HardwareKeys {
    /** Выключено, пока пользователь сам не включит. */
    const val DEFAULT_ENABLED = false

    /** Ключ в настройках; то же имя — в спеке и плане. */
    const val PREF_KEY = "volumeKeys"

    /** Эти клавиши — главная кнопка, когда переключатель включён. Остальные программа не трогает никогда. */
    fun consumes(keyCode: Int, enabled: Boolean): Boolean = enabled && (keyCode == KeyEvent.KEYCODE_VOLUME_UP ||
        keyCode == KeyEvent.KEYCODE_VOLUME_DOWN || keyCode == KeyEvent.KEYCODE_CAMERA)

    /** Действует только первое нажатие: повторы при удержании и отпускание — нет. */
    fun acts(action: Int, repeatCount: Int): Boolean = action == KeyEvent.ACTION_DOWN && repeatCount == 0

    /** Событие клавиши целиком: забрать ли его и нажимать ли главную кнопку. Нажимает только то, что забрано. */
    fun handle(keyCode: Int, action: Int, repeatCount: Int, enabled: Boolean): KeyHandling {
        val consumed = consumes(keyCode, enabled)
        return KeyHandling(consumed, pressed = consumed && acts(action, repeatCount))
    }

    /**
     * Что делает нажатие. [onFrameScreen] — на экране кадр (`ScreenState.isFrameScreen`: его не закрыли ⚙, пресеты, галерея, отладка,
     * просмотр снимка, карточка-подсказка). [photoMode] — фоторежим (иначе видео
     * или S&Q, у кнопки на экране это одно и то же). [ready] — камера на связи и готова. [photoBusy] — снимок идёт (фокус, спуск,
     * загрузка, сохранение; кнопка спуска на экране серая) или применяется пресет (серой она не станет, но обработчик такое
     * нажатие пропускает).
     * [recordPending] — камера не ответила на прошлое нажатие записи: висит «Запуск записи…» или «Остановка…» (кнопка записи на
     * экране серая) либо сам вызов ещё не вернулся после отказа по времени. Каждый режим смотрит на свою кнопку: в фото кнопки
     * записи на экране нет, в видео — кнопки спуска.
     */
    fun press(onFrameScreen: Boolean, photoMode: Boolean, ready: Boolean, photoBusy: Boolean, recordPending: Boolean): KeyAction = when {
        !onFrameScreen -> KeyAction.elsewhere
        !ready -> KeyAction.notReady
        photoMode -> if (photoBusy) KeyAction.busy else KeyAction.photo
        else -> if (recordPending) KeyAction.busy else KeyAction.record
    }
}
